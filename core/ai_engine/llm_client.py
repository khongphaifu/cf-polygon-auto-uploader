import json
import re
import time
from typing import Any, Dict, Optional, List
import requests


class LLMClient:
    """Client for interacting with Google Gemini API with seamless multi-model fallback."""

    FALLBACK_MODELS = [
        "gemini-3.1-flash-lite",
        "gemini-flash-lite-latest",
        "gemini-3.5-flash-lite",
        "gemini-3.8-flash",
        "gemini-3.7-flash",
        "gemini-3.1-pro-preview",
    ]

    def __init__(
        self,
        api_key: Any,
        backup_keys: Optional[List[str]] = None,
        model_name: str = "gemini-3.1-flash-lite",
        temperature: float = 0.2,
    ):
        self.api_keys_pool: List[str] = []
        if isinstance(api_key, list):
            self.api_keys_pool.extend([k.strip() for k in api_key if k and isinstance(k, str) and k.strip()])
        elif isinstance(api_key, str) and api_key.strip():
            self.api_keys_pool.append(api_key.strip())
        
        if backup_keys:
            for bk in backup_keys:
                if bk and isinstance(bk, str) and bk.strip() and bk.strip() not in self.api_keys_pool:
                    self.api_keys_pool.append(bk.strip())

        if not self.api_keys_pool:
            raise ValueError("No Gemini API key provided. Please configure gemini_api_key in config/config.yaml")

        self.api_key = self.api_keys_pool[0]
        # Map legacy/alias model names to verified active v1beta models
        normalized_name = (model_name or "").strip().lower()
        if normalized_name in [
            "", "gemini", "gemini-flash", "flash", "lite", "flash-lite",
            "gemini-2.5-flash", "gemini-2.0-flash",
            "3.6-flash", "gemini-3.6-flash", "3.6_flash",
            "3.7-flash", "gemini-3.7-flash",
            "gemini-3.5-flash", "gemini-3.5-flash-lite",
        ]:
            self.model_name = "gemini-3.1-flash-lite"
        elif normalized_name in ["3.1-pro", "gemini-3.1-pro", "3.1_pro", "gemini-2.5-pro", "pro"]:
            self.model_name = "gemini-3.1-pro-preview"
        else:
            self.model_name = model_name
        self.temperature = temperature
        self.session = requests.Session()

    def _clean_json_response(self, text: str) -> str:
        """Extract, clean and auto-repair raw JSON from LLM response."""
        text = text.strip()
        # Strip markdown ```json ... ```
        if text.startswith("```"):
            lines = text.splitlines()
            if lines[0].startswith("```"):
                lines = lines[1:]
            if lines and lines[-1].startswith("```"):
                lines = lines[:-1]
            text = "\n".join(lines).strip()
        
        # If still wrapped or containing extra text, find outermost { and }
        first_brace = text.find("{")
        if first_brace != -1:
            last_brace = text.rfind("}")
            if last_brace != -1 and last_brace > first_brace:
                text = text[first_brace:last_brace + 1]
            else:
                text = text[first_brace:]
                
        return text

    def _safe_json_loads(self, text: str) -> Dict[str, Any]:
        """Attempt to parse JSON with automatic truncation repair if needed."""
        cleaned = self._clean_json_response(text)
        try:
            return json.loads(cleaned)
        except json.JSONDecodeError:
            # Try basic auto-repair for truncated JSON: close open string and brackets
            repaired = cleaned
            quote_count = len(re.findall(r'(?<!\\)"', repaired))
            if quote_count % 2 == 1:
                repaired += '"'
            open_curly = repaired.count('{') - repaired.count('}')
            open_square = repaired.count('[') - repaired.count(']')
            if open_square > 0:
                repaired += ']' * open_square
            if open_curly > 0:
                repaired += '}' * open_curly
            try:
                return json.loads(repaired)
            except Exception:
                pass
            return json.loads(cleaned)

    def _extract_and_parse_response(self, response: requests.Response) -> Dict[str, Any]:
        """Extract generated text from a 200 OK Gemini response and parse JSON."""
        data = response.json()
        candidates = data.get("candidates", [])
        if not candidates:
            raise ValueError(f"No candidate generated by Gemini API: {data}")
        candidate = candidates[0]
        finish_reason = candidate.get("finishReason")
        parts = candidate.get("content", {}).get("parts", [])
        if not parts:
            raise ValueError(f"Candidate has no parts (finishReason: {finish_reason})")
        raw_text = parts[0].get("text", "")
        return self._safe_json_loads(raw_text)

    def _post_with_fallback(
        self,
        parts_list: List[Dict[str, Any]],
        system_instruction: Optional[str] = None,
        model_override: Optional[str] = None,
        timeout: int = 35,
        max_retries_per_model: int = 1,
    ) -> Dict[str, Any]:
        """Send generateContent request across models and API keys with fast failover."""
        chosen_model = model_override or self.model_name
        model_candidates: List[str] = [chosen_model]
        for m in self.FALLBACK_MODELS:
            if m not in model_candidates:
                model_candidates.append(m)

        payload: Dict[str, Any] = {
            "contents": [{"role": "user", "parts": parts_list}],
            "generationConfig": {
                "temperature": self.temperature,
                "maxOutputTokens": 8192,
                "responseMimeType": "application/json",
            },
            "safetySettings": [
                {"category": "HARM_CATEGORY_HARASSMENT", "threshold": "BLOCK_NONE"},
                {"category": "HARM_CATEGORY_HATE_SPEECH", "threshold": "BLOCK_NONE"},
                {"category": "HARM_CATEGORY_SEXUALLY_EXPLICIT", "threshold": "BLOCK_NONE"},
                {"category": "HARM_CATEGORY_DANGEROUS_CONTENT", "threshold": "BLOCK_NONE"},
                {"category": "HARM_CATEGORY_CIVIC_INTEGRITY", "threshold": "BLOCK_NONE"},
            ],
        }
        if system_instruction:
            payload["systemInstruction"] = {"parts": [{"text": system_instruction}]}

        last_error: Optional[Exception] = None
        for current_key in list(self.api_keys_pool):
            for candidate_model in model_candidates:
                url = f"https://generativelanguage.googleapis.com/v1beta/models/{candidate_model}:generateContent?key={current_key}"
                for attempt in range(1, max_retries_per_model + 1):
                    try:
                        response = self.session.post(
                            url,
                            json=payload,
                            headers={"Content-Type": "application/json"},
                            timeout=timeout,
                        )
                        if response.status_code == 200:
                            result = self._extract_and_parse_response(response)
                            if not model_override:
                                self.model_name = candidate_model
                            # Sticky rotation: promote working key to front for subsequent calls
                            if current_key != self.api_keys_pool[0]:
                                self.api_keys_pool = [current_key] + [k for k in self.api_keys_pool if k != current_key]
                                self.api_key = current_key
                            return result
                        elif response.status_code in (429, 503):
                            last_error = RuntimeError(f"{candidate_model} returned HTTP {response.status_code} (busy/rate limit)")
                            if attempt < max_retries_per_model:
                                time.sleep(2 * attempt)
                            else:
                                break
                        elif response.status_code == 404:
                            last_error = RuntimeError(f"{candidate_model} returned 404 Not Found")
                            break
                        else:
                            last_error = RuntimeError(f"HTTP {response.status_code} on {candidate_model}: {response.text[:200]}")
                            break
                    except Exception as e:
                        last_error = e
                        if attempt < max_retries_per_model:
                            time.sleep(1)

        raise RuntimeError(f"Failed to generate content with Gemini API across all keys and models: {last_error}")

    def generate_json(
        self,
        prompt: str,
        system_instruction: Optional[str] = None,
        model_override: Optional[str] = None,
        max_retries: int = 1,
    ) -> Dict[str, Any]:
        """Send text prompt to Gemini API with fast model fallback and key rotation."""
        return self._post_with_fallback(
            parts_list=[{"text": prompt}],
            system_instruction=system_instruction,
            model_override=model_override,
            timeout=35,
            max_retries_per_model=max_retries,
        )

    def generate_from_image(
        self,
        prompt: str,
        image_bytes: bytes,
        mime_type: str = "image/png",
        max_retries: int = 1,
    ) -> Dict[str, Any]:
        """Send multimodal vision/PDF request to Gemini API with fast fallback and key rotation."""
        import base64

        img_b64 = base64.b64encode(image_bytes).decode("utf-8")
        return self._post_with_fallback(
            parts_list=[
                {"text": prompt},
                {"inlineData": {"mimeType": mime_type, "data": img_b64}},
            ],
            timeout=45,
            max_retries_per_model=max_retries,
        )
